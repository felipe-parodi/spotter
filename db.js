/* ---------------- HIIT blocks ----------------
   Guided interval sequences run by the in-app timer. hard=true intervals
   get the "push" styling; every transition beeps. */
function hiitRep(n, steps) {
  const out = [];
  for (let i = 0; i < n; i++) steps.forEach(s => out.push(s));
  return out;
}

